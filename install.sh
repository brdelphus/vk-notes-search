#!/usr/bin/env bash
# vk installer — sets up an isolated venv, puts `vk` on PATH, optionally
# registers a Hermes Agent skill so the agent knows the engine exists.
#
#   ./install.sh                 install the `vk` command
#   ./install.sh --skill         also drop a Hermes skill (agent-side usage)
#   ./install.sh --prefix DIR    where the wrapper goes (default ~/.local/bin)
#   ./install.sh --uninstall     remove everything this script created
#
# Idempotent: safe to run again to upgrade chromadb or refresh the skill.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PREFIX="$HOME/.local/bin"
DATADIR="$HOME/.local/share/vk"
VENV="$DATADIR/venv"
WITH_SKILL=0
UNINSTALL=0

while [ $# -gt 0 ]; do
  case "$1" in
    --skill)      WITH_SKILL=1 ;;
    --prefix)     PREFIX="${2:?--prefix needs a directory}"; shift ;;
    --uninstall)  UNINSTALL=1 ;;
    -h|--help)    sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *)            echo "unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done

say()  { printf '  %s\n' "$*"; }
ok()   { printf '  \033[32mok\033[0m %s\n' "$*"; }
err()  { printf '  \033[31merror\033[0m %s\n' "$*" >&2; }

# ---------------------------------------------------------------- uninstall ---
if [ "$UNINSTALL" = 1 ]; then
  echo "uninstalling vk"
  rm -f  "$PREFIX/vk"                       && ok "removed $PREFIX/vk"
  rm -rf "$DATADIR"                         && ok "removed $DATADIR"
  for f in "$HOME"/.hermes/skills/*/vk-notes*/SKILL.md \
           "$HOME"/.hermes/profiles/*/skills/*/vk-notes*/SKILL.md; do
    [ -e "$f" ] || continue
    rm -rf "$(dirname "$f")"                && ok "removed skill $(dirname "$f")"
  done
  echo
  say "Your notes under categorias/ were NOT touched."
  say "The vector DB cache in ~/.cache/vk was NOT touched — delete it manually if you want."
  exit 0
fi

# ------------------------------------------------------------------ preflight --
echo "installing vk"

PY=""
for cand in python3 python; do
  if command -v "$cand" >/dev/null 2>&1; then
    if "$cand" -c 'import sys; sys.exit(0 if sys.version_info >= (3,9) else 1)' 2>/dev/null; then
      PY="$cand"; break
    fi
  fi
done
if [ -z "$PY" ]; then
  err "python 3.9+ not found on PATH"
  exit 1
fi
ok "python: $("$PY" --version 2>&1) ($(command -v "$PY"))"

[ -f "$REPO/vk.py" ] || { err "vk.py not found next to this installer"; exit 1; }

# ---------------------------------------------------------------------- venv --
mkdir -p "$DATADIR"
if [ ! -x "$VENV/bin/python" ]; then
  "$PY" -m venv "$VENV"
  ok "created venv at $VENV"
else
  ok "venv already present at $VENV"
fi

say "installing chromadb (this pulls onnxruntime, ~100MB — first run is slow)"
"$VENV/bin/python" -m pip install --quiet --upgrade pip
"$VENV/bin/python" -m pip install --quiet -r "$REPO/requirements.txt"
ok "chromadb $("$VENV/bin/python" -c 'import chromadb; print(chromadb.__version__)')"

# ------------------------------------------------------------------- wrapper --
mkdir -p "$PREFIX"
cat > "$PREFIX/vk" <<WRAPPER
#!/usr/bin/env bash
# generated by vk install.sh — do not edit, re-run the installer instead
exec "$VENV/bin/python" "$REPO/vk.py" "\$@"
WRAPPER
chmod +x "$PREFIX/vk"
ok "wrapper: $PREFIX/vk -> $REPO/vk.py"

case ":$PATH:" in
  *":$PREFIX:"*) ok "$PREFIX is on PATH" ;;
  *) say "WARNING: $PREFIX is not on PATH — add it, e.g."
     say "  echo 'export PATH=\"\$HOME/.local/bin:\$PATH\"' >> ~/.bashrc" ;;
esac

# --------------------------------------------------------------- hermes skill --
if [ "$WITH_SKILL" = 1 ]; then
  # prefer a running profile's skill dir; fall back to the default location
  SKILLROOT=""
  for d in "$HOME"/.hermes/profiles/*/skills; do
    [ -d "$d" ] && SKILLROOT="$d" && break
  done
  [ -z "$SKILLROOT" ] && SKILLROOT="$HOME/.hermes/skills"
  DEST="$SKILLROOT/knowledge/vk-notes"
  mkdir -p "$DEST"
  cat > "$DEST/SKILL.md" <<'SKILL'
---
name: vk-notes
description: "Use when recalling a fix, config or procedure from your markdown notes."
version: 1.0.0
metadata:
  hermes:
    tags: [memory, knowledge-base, search, markdown, chromadb]
---

# vk — markdown notes recall

A local semantic search engine over a folder of markdown notes. Use it to
recover *"how did I solve this before"* when you no longer remember the exact
words, instead of grepping for terms that no longer match.

## Trigger

- A technical question whose answer is probably already written down
- Before making an infrastructure change, to recall prior context
- "where did I document", "how did I fix", "what was the workaround"

## Usage

```bash
vk sync                     # git pull + reindex — ALWAYS first
vk query "text"             # semantic search
vk query "text" --cat infra # filtered by category
vk query "text" -n 3        # top-N (default 5)
vk index                    # reindex after editing notes
vk stats                    # what is indexed
```

`sync` before `query` is not optional: it pulls notes written on other machines
and reindexes. Without it the search reads a stale local cache.

## How results read

```
### infra/nginx-wrong-site.md  (dist 0.287)
<except of the best-matching section>
```

Distance is cosine: **lower is better**. Under 0.35 is a strong hit, 0.4–0.6 is
usually the right note, above ~0.7 the engine found nothing useful — say so
instead of quoting a bad match as fact.

Results are grouped by note, so the answer is the note, not a fragment.

## Installing

```bash
git clone https://github.com/brdelphus/vk-notes-search.git
cd vk-notes-search && ./install.sh --skill
```

## Pitfalls

- **A note missing from the top-5 is not a note missing from the index.** Check
  with `vk stats` before concluding the knowledge does not exist.
- **First `index` looks frozen at 0%** for ~40 s while the embedding model
  downloads (~79 MB). Do not kill it.
- **The note is the source of truth, the vector DB is a cache.** Never treat the
  cache as authoritative; rebuild it with `vk index`.
SKILL
  ok "skill: $DEST/SKILL.md"
fi

# ---------------------------------------------------------------------- smoke --
echo
say "smoke test"
SMOKE="$(mktemp -d)"
trap 'rm -rf "$SMOKE"' EXIT
if VK_DB="$SMOKE/db" "$VENV/bin/python" "$REPO/vk.py" index >/dev/null 2>&1; then
  ok "index runs"
  if VK_DB="$SMOKE/db" "$VENV/bin/python" "$REPO/vk.py" query "problem" -n 1 2>/dev/null | grep -q '^###'; then
    ok "query returns results"
  else
    say "query returned nothing (fine if categorias/ is empty)"
  fi
else
  err "index failed — check $VENV/bin/python $REPO/vk.py index"
  exit 1
fi

echo
echo "done."
say "add notes under $REPO/categorias/<category>/<note>.md"
say "then: vk index && vk query \"...\""
